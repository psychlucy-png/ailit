function waveBlocks(t) {
  return WAVES[t].map(id => {
    const b = BLOCK[id];
    const items = b.items.filter(it => !it.waves || it.waves.includes(t));
    return { ...b, items, prefix: (t > 1 || REPEATED.has(id)) ? `t${t}_` : "" };
  });
}

